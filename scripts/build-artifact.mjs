function quoteIdentifier(identifier) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function sqliteType(rows, field) {
  const values = rows.map((row) => row[field]).filter((value) => value != null);
  if (values.length && values.every((value) => typeof value === "number")) {
    return values.every(Number.isInteger) ? "INTEGER" : "REAL";
  }
  if (values.length && values.every((value) => typeof value === "boolean")) return "INTEGER";
  return "TEXT";
}

function materializeDatasetsWithSql(rawDatasets, queries) {
  const database = new DatabaseSync(":memory:");
  const queryNames = Object.keys(queries).sort();
  const datasetNames = Object.keys(rawDatasets).sort();
  if (JSON.stringify(queryNames) !== JSON.stringify(datasetNames)) {
    throw new Error(
      `SQL query names must match dashboard datasets: ${JSON.stringify({ queryNames, datasetNames })}`,
    );
  }

  for (const [name, rows] of Object.entries(rawDatasets)) {
    if (!Array.isArray(rows) || rows.length === 0) {
      throw new Error(`source dataset ${name} must contain at least one row`);
    }
    const fields = Object.keys(rows[0]);
    const columns = fields
      .map((field) => `${quoteIdentifier(field)} ${sqliteType(rows, field)}`)
      .join(", ");
    database.exec(`CREATE TABLE ${quoteIdentifier(name)} (${columns})`);
    const placeholders = fields.map(() => "?").join(", ");
    const insert = database.prepare(
      `INSERT INTO ${quoteIdentifier(name)} (${fields.map(quoteIdentifier).join(", ")}) VALUES (${placeholders})`,
    );
    for (const row of rows) {
      insert.run(
        ...fields.map((field) => {
          const value = row[field];
          return typeof value === "boolean" ? Number(value) : value;
        }),
      );
    }
  }

  const keyFields = {
    summary: ["universal_plugins"],
    inventory_planes: ["plane", "total"],
    tui_categories: ["category", "count"],
    third_party_categories: ["category", "plugin_count", "provider_count"],
    top_third_party_providers: ["provider", "plugin_count", "category_count"],
    repo_categories: ["category", "count"],
    category_positioning: ["category", "universal_count", "git_count", "relative_emphasis"],
    cli_marketplaces: ["marketplace", "total"],
    component_counts_chart: ["component", "count"],
    package_index: ["name", "provider", "provider_scope", "category"],
    package_archetypes: ["architecture", "package_count"],
    interfaces: ["layer", "count"],
    api_exclusions: ["plugin"],
  };
  const datasets = {};
  const rowCounts = {};
  for (const [name, sql] of Object.entries(queries)) {
    const rows = database.prepare(sql).all();
    if (rows.length !== rawDatasets[name].length) {
      throw new Error(
        `${name} SQL row count ${rows.length} does not match normalized source ${rawDatasets[name].length}`,
      );
    }
    for (const field of keyFields[name]) {
      const nulls = rows.filter((row) => row[field] == null).length;
      if (nulls !== 0) throw new Error(`${name}.${field} has ${nulls} unexpected NULL values`);
    }
    datasets[name] = rows;
    rowCounts[name] = rows.length;
  }
  database.close();
  return { datasets, rowCounts };
}

